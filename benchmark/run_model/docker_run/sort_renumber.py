import argparse
parser = argparse.ArgumentParser()
parser.add_argument("-i", "--input", help="input pdb file")
parser.add_argument("-o", "--output", help="output pdb file, without pdb suffix")
args = parser.parse_args()
input_pdb = args.input
out_pdb = args.output
###sort
import os 
os.system(f"/home/ab/miniconda3/bin/pdb_sort -R {input_pdb} > {out_pdb}_sort.pdb")

###renum
from renum import renumber
h,l,ag = renumber(f"{out_pdb}_sort.pdb", f"{out_pdb}_chothia.pdb", return_other_chains=True)

###add header
header = f"""REMARK   5 CHOTHIA RENUMBERED STRUCTURE 8X0T GENERATED BY SABDAB
REMARK   5 ANTIBODY CHAINS ARE RENUMBERED IN THE VARIABLE REGIONS ONLY
REMARK   5 NON ANTIBODY CHAINS ARE LEFT WITH RESIDUE IDS AS IN PDB
REMARK   5 PAIRED_HL HCHAIN={h[0]} AGCHAIN={ag[0]} AGTYPE=PROTEIN\n"""

append_copy = open(f"{out_pdb}_chothia.pdb", "r")
original_text = append_copy.read()
append_copy.close()

append_copy = open(f"{out_pdb}_chothia.pdb", "w")
append_copy.write(header)
append_copy.write(original_text)
append_copy.close()

###去掉 TER 和 END
os.system(f"sed -i '/TER/d' {out_pdb}_chothia.pdb")
os.system(f"sed -i '/END/d' {out_pdb}_chothia.pdb")
