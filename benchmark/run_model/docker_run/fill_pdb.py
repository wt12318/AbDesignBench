from Bio.PDB import PDBParser, PDBIO, Select
import numpy as np
from Bio.SeqUtils import seq1
from abnumber import Chain
from Bio import PDB
import copy
import argparse
parser = argparse.ArgumentParser()
parser.add_argument("-o", "--origin", help="original input pdb file")
parser.add_argument("-g", "--gen", help="generated input pdb file")
parser.add_argument("-a", "--hchain", help="h chain ID of ori")
parser.add_argument("-b", "--ghchain", help="h chain ID of gen")
parser.add_argument("-s", "--scheme", help="number scheme")
parser.add_argument("-p", "--output", help="output pdb")
args = parser.parse_args()
pdb_origin_file = args.origin
pdb_gen_file = args.gen
hchain = args.hchain
ghchain = args.ghchain
scheme = args.scheme ##chothia
outpdb = args.output

p = PDBParser(QUIET=True)
origin_struc = p.get_structure("protein", pdb_origin_file)
hchain_origin = origin_struc[0][hchain]
gen_struc = p.get_structure("protein", pdb_gen_file)
model_gen = gen_struc[0][ghchain]
##HCDR3的氨基酸残基
chains_seq = {chain.id:seq1(''.join(residue.resname for residue in chain)) for chain in origin_struc.get_chains()}
chain_resid = {chain.id:[residue.id[1] for residue in chain] for chain in origin_struc.get_chains()}
chain_anno = Chain.multiple_domains(chains_seq[hchain], scheme=scheme)
for i in chain_anno:
    if i.chain_type == "H":
        hseq = i
hcdr3_start = chains_seq[hchain].find(hseq.cdr3_seq)
hcdr3_resid = chain_resid[hchain][hcdr3_start:hcdr3_start+len(hseq.cdr3_seq)]

###删除原来的HCDR3
for res in list(hchain_origin):
    if res.get_id()[1] in hcdr3_resid:
        hchain_origin.detach_child(res.get_id())

###加上生成的
for i, res in enumerate(model_gen.get_residues()):
    res.id = (' ', hcdr3_resid[i], ' ')
    hchain_origin.add(res) 

###保存
io = PDB.PDBIO()
io.set_structure(origin_struc)
io.save(f"{outpdb}.pdb")

###sort
import os 
os.system(f"/home/ab/miniconda3/bin/pdb_sort -R {outpdb}.pdb > {outpdb}_sort.pdb")

###renum
from renum import renumber
h,l,ag = renumber(f"{outpdb}_sort.pdb", f"{outpdb}_chothia.pdb", return_other_chains=True)

###add header
header = f"""REMARK   5 CHOTHIA RENUMBERED STRUCTURE 8X0T GENERATED BY SABDAB
REMARK   5 ANTIBODY CHAINS ARE RENUMBERED IN THE VARIABLE REGIONS ONLY
REMARK   5 NON ANTIBODY CHAINS ARE LEFT WITH RESIDUE IDS AS IN PDB
REMARK   5 PAIRED_HL HCHAIN={h[0]} AGCHAIN={ag[0]} AGTYPE=PROTEIN\n"""

append_copy = open(f"{outpdb}_chothia.pdb", "r")
original_text = append_copy.read()
append_copy.close()

append_copy = open(f"{outpdb}_chothia.pdb", "w")
append_copy.write(header)
append_copy.write(original_text)
append_copy.close()

###去掉 TER 和 END
os.system(f"sed -i '/TER/d' {outpdb}_chothia.pdb")
os.system(f"sed -i '/END/d' {outpdb}_chothia.pdb")





        

